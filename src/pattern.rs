#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum FillStyle {
    #[default]
    Solid,
    Hatch(HatchStyle),
}
#[derive(Clone, Copy, Debug)]
pub struct FillSource {
    pub style: FillStyle,
    pub foreground: Pixel,
    pub background: Pixel,
}
impl From<Pixel> for FillSource {
    fn from(color: Pixel) -> Self {
        Self {
            style: FillStyle::Solid,
            foreground: color,
            background: [0; 4],
        }
    }
}
impl FillSource {
    pub fn sample(self, x: i32, y: i32) -> Pixel {
        match self.style {
            FillStyle::Solid => self.foreground,
            FillStyle::Hatch(style) => {
                let pixel = ToolBlend::Overwrite.apply(
                    self.background,
                    self.foreground,
                    style.coverage(x, y),
                );
                if pixel[3] == 0 { [0; 4] } else { pixel }
            }
        }
    }
    pub fn tile(self) -> Option<tiny_skia::Pixmap> {
        if self.style == FillStyle::Solid {
            return None;
        }
        let mut tile = tiny_skia::Pixmap::new(8, 8)?;
        for (i, p) in tile.pixels_mut().iter_mut().enumerate() {
            let c = self.sample((i % 8) as i32, (i / 8) as i32);
            *p = tiny_skia::ColorU8::from_rgba(c[0], c[1], c[2], c[3]).premultiply();
        }
        Some(tile)
    }
}
